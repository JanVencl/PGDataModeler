package com.datagocar.ddl;

import com.datagocar.model.CheckConstraint;
import com.datagocar.model.Column;
import com.datagocar.model.DataModel;
import com.datagocar.model.EnumType;
import com.datagocar.model.Identity;
import com.datagocar.model.Index;
import com.datagocar.model.Model;
import com.datagocar.model.Relationship;
import com.datagocar.model.Table;
import com.datagocar.model.View;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.TreeSet;
import java.util.stream.Collectors;

/**
 * Generates PostgreSQL DDL. Output order: schemas, enum types, tables (with primary key, unique and
 * check constraints, comments), seed rows of lookup tables, foreign keys, indexes, views (in dependency order). Foreign keys come last so table order never matters.
 */
public final class PostgresDdlGenerator {

    /** One logical unit of DDL (may contain several statements, e.g. a table plus its comments). */
    public record DdlUnit(String id, String sql) {
    }

    public String generate(DataModel model) {
        StringBuilder sb = new StringBuilder();
        sb.append("-- ").append(model.name()).append('\n');
        sb.append("-- Generated by DataGocar for PostgreSQL\n\n");
        sb.append(units(model).stream().map(DdlUnit::sql).collect(Collectors.joining("\n\n")));
        sb.append('\n');
        return sb.toString();
    }

    public List<DdlUnit> units(DataModel model) {
        List<DdlUnit> units = new ArrayList<>();
        for (String schema : nonPublicSchemas(model)) {
            units.add(new DdlUnit("schema-" + schema,
                    "CREATE SCHEMA IF NOT EXISTS " + Identifiers.quote(schema) + ";"));
        }
        for (EnumType e : sortedEnums(model)) {
            String values = e.values().stream().map(Identifiers::literal).collect(Collectors.joining(", "));
            units.add(new DdlUnit("enum-" + e.schema() + "." + e.name(),
                    "CREATE TYPE " + Identifiers.qualified(e.schema(), e.name()) + " AS ENUM (" + values + ");"));
        }
        for (Table t : sortedTables(model)) {
            units.add(new DdlUnit("table-" + t.schema() + "." + t.name(), createTable(t)));
        }
        // Seed rows before the foreign keys, so lookup tables referencing each other load in any order.
        for (Table t : sortedTables(model)) {
            if (SeedData.has(t)) {
                units.add(new DdlUnit(dataUnitId(t), SeedData.insert(t)));
            }
        }
        for (Relationship r : model.relationships()) {
            units.add(new DdlUnit("fk-" + Naming.foreignKey(model, r), foreignKey(model, r)));
        }
        for (Table t : sortedTables(model)) {
            for (Index i : t.indexes()) {
                units.add(new DdlUnit("index-" + t.schema() + "." + Naming.index(t, i), createIndex(t, i)));
            }
        }
        // Views last, each after the views it reads.
        for (View v : ViewDependencies.creationOrder(model)) {
            units.add(new DdlUnit(viewUnitId(v), createView(v)));
        }
        return units;
    }

    static String dataUnitId(Table t) {
        return "data-" + t.schema() + "." + t.name();
    }

    static boolean isDataUnit(DdlUnit unit) {
        return unit.id().startsWith("data-");
    }

    static String viewUnitId(View v) {
        return (v.materialized() ? "mview-" : "view-") + v.schema() + "." + v.name();
    }

    /** Units that are safe to re-run when they change: seed upserts and CREATE OR REPLACE VIEW. */
    static boolean isRerunnable(DdlUnit unit) {
        return isDataUnit(unit) || unit.id().startsWith("view-");
    }

    static String viewKeyword(View v) {
        return v.materialized() ? "MATERIALIZED VIEW" : "VIEW";
    }

    String createView(View v) {
        String name = Identifiers.qualified(v.schema(), v.name());
        StringBuilder sb = new StringBuilder(v.materialized() ? "CREATE MATERIALIZED VIEW " : "CREATE OR REPLACE VIEW ")
                .append(name).append(" AS\n").append(v.definition()).append(';');
        if (!Model.isBlank(v.comment())) {
            sb.append("\nCOMMENT ON ").append(viewKeyword(v)).append(' ').append(name)
                    .append(" IS ").append(Identifiers.literal(v.comment())).append(';');
        }
        return sb.toString();
    }

    String createTable(Table t) {
        String qualifiedName = Identifiers.qualified(t.schema(), t.name());
        List<String> lines = new ArrayList<>();
        for (Column c : t.columns()) {
            lines.add("    " + columnDefinition(c));
        }
        List<Column> pk = t.primaryKeyColumns();
        if (!pk.isEmpty()) {
            lines.add("    CONSTRAINT " + Identifiers.quote(Naming.primaryKey(t)) + " PRIMARY KEY ("
                    + pk.stream().map(c -> Identifiers.quote(c.name())).collect(Collectors.joining(", ")) + ")");
        }
        for (Column c : t.columns()) {
            if (c.unique() && !(c.primaryKey() && pk.size() == 1)) {
                lines.add("    CONSTRAINT " + Identifiers.quote(Naming.unique(t, c)) + " UNIQUE (" + Identifiers.quote(c.name()) + ")");
            }
        }
        for (int i = 0; i < t.checks().size(); i++) {
            CheckConstraint check = t.checks().get(i);
            if (!Model.isBlank(check.expression())) {
                lines.add("    CONSTRAINT " + Identifiers.quote(Naming.check(t, check, i)) + " CHECK (" + check.expression().trim() + ")");
            }
        }
        StringBuilder sb = new StringBuilder("CREATE TABLE ").append(qualifiedName).append(" (\n");
        sb.append(String.join(",\n", lines)).append("\n);");
        if (!Model.isBlank(t.comment())) {
            sb.append("\nCOMMENT ON TABLE ").append(qualifiedName).append(" IS ").append(Identifiers.literal(t.comment())).append(';');
        }
        for (Column c : t.columns()) {
            if (!Model.isBlank(c.comment())) {
                sb.append("\nCOMMENT ON COLUMN ").append(qualifiedName).append('.').append(Identifiers.quote(c.name()))
                        .append(" IS ").append(Identifiers.literal(c.comment())).append(';');
            }
        }
        return sb.toString();
    }

    String columnDefinition(Column c) {
        StringBuilder sb = new StringBuilder(Identifiers.quote(c.name())).append(' ').append(c.type());
        if (c.identity() == Identity.ALWAYS) {
            sb.append(" GENERATED ALWAYS AS IDENTITY");
        } else if (c.identity() == Identity.BY_DEFAULT) {
            sb.append(" GENERATED BY DEFAULT AS IDENTITY");
        } else if (!Model.isBlank(c.defaultValue())) {
            sb.append(" DEFAULT ").append(c.defaultValue().trim());
        }
        if (c.effectivelyNotNull()) {
            sb.append(" NOT NULL");
        }
        return sb.toString();
    }

    String foreignKey(DataModel model, Relationship r) {
        Table from = model.table(r.fromTableId()).orElseThrow();
        Table to = model.table(r.toTableId()).orElseThrow();
        String fromCols = r.columns().stream()
                .map(p -> Identifiers.quote(from.column(p.fromColumnId()).orElseThrow().name()))
                .collect(Collectors.joining(", "));
        String toCols = r.columns().stream()
                .map(p -> Identifiers.quote(to.column(p.toColumnId()).orElseThrow().name()))
                .collect(Collectors.joining(", "));
        StringBuilder sb = new StringBuilder("ALTER TABLE ").append(Identifiers.qualified(from.schema(), from.name()))
                .append("\n    ADD CONSTRAINT ").append(Identifiers.quote(Naming.foreignKey(model, r)))
                .append(" FOREIGN KEY (").append(fromCols).append(")")
                .append("\n    REFERENCES ").append(Identifiers.qualified(to.schema(), to.name()))
                .append(" (").append(toCols).append(")");
        if (r.onDelete() != com.datagocar.model.FkAction.NO_ACTION) {
            sb.append(" ON DELETE ").append(r.onDelete().sql());
        }
        if (r.onUpdate() != com.datagocar.model.FkAction.NO_ACTION) {
            sb.append(" ON UPDATE ").append(r.onUpdate().sql());
        }
        return sb.append(';').toString();
    }

    String createIndex(Table t, Index i) {
        StringBuilder sb = new StringBuilder("CREATE ");
        if (i.unique()) {
            sb.append("UNIQUE ");
        }
        sb.append("INDEX ").append(Identifiers.quote(Naming.index(t, i)))
                .append(" ON ").append(Identifiers.qualified(t.schema(), t.name()));
        if (!"btree".equals(i.method())) {
            sb.append(" USING ").append(i.method());
        }
        sb.append(" (").append(Naming.columnNames(t, i.columnIds()).stream().map(Identifiers::quote)
                .collect(Collectors.joining(", "))).append(')');
        if (!Model.isBlank(i.where())) {
            sb.append(" WHERE ").append(i.where().trim());
        }
        return sb.append(';').toString();
    }

    static List<String> nonPublicSchemas(DataModel model) {
        TreeSet<String> schemas = new TreeSet<>();
        model.tables().forEach(t -> schemas.add(t.schema()));
        model.enums().forEach(e -> schemas.add(e.schema()));
        schemas.remove(Model.DEFAULT_SCHEMA);
        return List.copyOf(schemas);
    }

    static List<Table> sortedTables(DataModel model) {
        return model.tables().stream()
                .sorted(Comparator.comparing(Table::schema).thenComparing(Table::name))
                .toList();
    }

    static List<EnumType> sortedEnums(DataModel model) {
        return model.enums().stream()
                .sorted(Comparator.comparing(EnumType::schema).thenComparing(EnumType::name))
                .toList();
    }
}
