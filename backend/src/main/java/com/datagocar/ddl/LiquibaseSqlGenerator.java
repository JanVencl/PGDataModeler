package com.datagocar.ddl;

import com.datagocar.model.DataModel;

/** Generates a Liquibase "formatted SQL" changelog: plain PostgreSQL DDL split into changesets. */
public final class LiquibaseSqlGenerator {

    private final PostgresDdlGenerator ddl = new PostgresDdlGenerator();

    public String generate(DataModel model, String author) {
        StringBuilder sb = new StringBuilder("--liquibase formatted sql\n");
        sb.append("-- ").append(model.name()).append(" (generated by DataGocar)\n");
        for (var unit : ddl.units(model)) {
            sb.append("\n--changeset ").append(author).append(':').append(unit.id().replace(' ', '_'));
            if (PostgresDdlGenerator.isRerunnable(unit)) {
                // Seed upserts and CREATE OR REPLACE VIEW: re-run whenever they change.
                sb.append(" runOnChange:true");
            }
            sb.append('\n');
            sb.append(unit.sql()).append('\n');
        }
        return sb.toString();
    }
}
