package com.datagocar.ddl;

import com.datagocar.model.CheckConstraint;
import com.datagocar.model.Column;
import com.datagocar.model.DataModel;
import com.datagocar.model.EnumType;
import com.datagocar.model.FkAction;
import com.datagocar.model.Identity;
import com.datagocar.model.Index;
import com.datagocar.model.Model;
import com.datagocar.model.Relationship;
import com.datagocar.model.Table;
import com.datagocar.model.View;

import java.util.List;
import java.util.stream.Collectors;

/**
 * Generates a Liquibase XML changelog using native change types where Liquibase has them
 * (createTable, addForeignKeyConstraint, createIndex) and {@code <sql>} with explicit rollback where it
 * does not (schemas, enum types, check constraints, non-btree or partial indexes, seed rows of lookup tables, materialized views).
 */
public final class LiquibaseXmlGenerator {

    private final PostgresDdlGenerator ddl = new PostgresDdlGenerator();

    public String generate(DataModel model, String author) {
        Xml x = new Xml(author);
        x.line(0, "<?xml version=\"1.0\" encoding=\"UTF-8\"?>");
        x.line(0, "<!-- " + comment(model.name()) + " (generated by DataGocar) -->");
        x.line(0, "<databaseChangeLog");
        x.line(1, "xmlns=\"http://www.liquibase.org/xml/ns/dbchangelog\"");
        x.line(1, "xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\"");
        x.line(1, "xsi:schemaLocation=\"http://www.liquibase.org/xml/ns/dbchangelog "
                + "http://www.liquibase.org/xml/ns/dbchangelog/dbchangelog-latest.xsd\">");

        for (String schema : PostgresDdlGenerator.nonPublicSchemas(model)) {
            x.sqlChangeSet("schema-" + schema,
                    "CREATE SCHEMA IF NOT EXISTS " + Identifiers.quote(schema) + ";",
                    "DROP SCHEMA " + Identifiers.quote(schema) + ";");
        }
        for (EnumType e : PostgresDdlGenerator.sortedEnums(model)) {
            String name = Identifiers.qualified(e.schema(), e.name());
            x.sqlChangeSet("enum-" + e.schema() + "." + e.name(),
                    "CREATE TYPE " + name + " AS ENUM ("
                            + e.values().stream().map(Identifiers::literal).collect(Collectors.joining(", ")) + ");",
                    "DROP TYPE " + name + ";");
        }
        for (Table t : PostgresDdlGenerator.sortedTables(model)) {
            createTable(x, t);
            for (int i = 0; i < t.checks().size(); i++) {
                CheckConstraint c = t.checks().get(i);
                if (Model.isBlank(c.expression())) {
                    continue;
                }
                String table = Identifiers.qualified(t.schema(), t.name());
                String name = Identifiers.quote(Naming.check(t, c, i));
                x.sqlChangeSet("check-" + t.schema() + "." + Naming.check(t, c, i),
                        "ALTER TABLE " + table + " ADD CONSTRAINT " + name + " CHECK (" + c.expression().trim() + ");",
                        "ALTER TABLE " + table + " DROP CONSTRAINT " + name + ";");
            }
        }
        for (Table t : PostgresDdlGenerator.sortedTables(model)) {
            if (SeedData.has(t)) {
                // An idempotent upsert, re-run whenever the rows change.
                x.sqlChangeSet(PostgresDdlGenerator.dataUnitId(t), SeedData.insert(t), SeedData.delete(t), true);
            }
        }
        for (Relationship r : model.relationships()) {
            foreignKey(x, model, r);
        }
        for (Table t : PostgresDdlGenerator.sortedTables(model)) {
            for (Index i : t.indexes()) {
                createIndex(x, t, i);
            }
        }
        for (View v : ViewDependencies.creationOrder(model)) {
            createView(x, v);
        }
        x.line(0, "</databaseChangeLog>");
        return x.toString();
    }

    private void createView(Xml x, View v) {
        String name = Identifiers.qualified(v.schema(), v.name());
        String id = PostgresDdlGenerator.viewUnitId(v);
        if (v.materialized()) {
            // Liquibase has no materialized-view change type.
            x.sqlChangeSet(id, ddl.createView(v), "DROP MATERIALIZED VIEW " + name + ";");
            return;
        }
        x.openChangeSet(id, true);
        x.line(2, "<createView" + attr("schemaName", v.schema()) + attr("viewName", v.name())
                + attr("replaceIfExists", "true") + "><![CDATA[" + Xml.cdata(v.definition()) + "]]></createView>");
        if (!Model.isBlank(v.comment())) {
            x.line(2, "<sql><![CDATA[COMMENT ON VIEW " + name + " IS " + Xml.cdata(Identifiers.literal(v.comment())) + ";]]></sql>");
        }
        x.line(2, "<rollback>");
        x.line(3, "<dropView" + attr("schemaName", v.schema()) + attr("viewName", v.name()) + "/>");
        x.line(2, "</rollback>");
        x.closeChangeSet();
    }

    private void createTable(Xml x, Table t) {
        x.openChangeSet("table-" + t.schema() + "." + t.name());
        x.line(2, "<createTable" + attr("schemaName", t.schema()) + attr("tableName", t.name())
                + optAttr("remarks", t.comment()) + ">");
        List<Column> pk = t.primaryKeyColumns();
        for (Column c : t.columns()) {
            StringBuilder col = new StringBuilder("<column").append(attr("name", c.name())).append(attr("type", c.type()));
            if (c.identity() != Identity.NONE) {
                col.append(attr("autoIncrement", "true"))
                        .append(attr("generationType", c.identity() == Identity.ALWAYS ? "ALWAYS" : "BY DEFAULT"));
            } else if (!Model.isBlank(c.defaultValue())) {
                col.append(attr("defaultValueComputed", c.defaultValue().trim()));
            }
            col.append(optAttr("remarks", c.comment()));
            StringBuilder cons = new StringBuilder();
            if (c.primaryKey()) {
                cons.append(attr("primaryKey", "true")).append(attr("primaryKeyName", Naming.primaryKey(t)));
            }
            if (c.effectivelyNotNull()) {
                cons.append(attr("nullable", "false"));
            }
            if (c.unique() && !(c.primaryKey() && pk.size() == 1)) {
                cons.append(attr("unique", "true")).append(attr("uniqueConstraintName", Naming.unique(t, c)));
            }
            if (cons.isEmpty()) {
                x.line(3, col + "/>");
            } else {
                x.line(3, col + ">");
                x.line(4, "<constraints" + cons + "/>");
                x.line(3, "</column>");
            }
        }
        x.line(2, "</createTable>");
        x.closeChangeSet();
    }

    private void foreignKey(Xml x, DataModel model, Relationship r) {
        Table from = model.table(r.fromTableId()).orElseThrow();
        Table to = model.table(r.toTableId()).orElseThrow();
        String name = Naming.foreignKey(model, r);
        x.openChangeSet("fk-" + name);
        StringBuilder sb = new StringBuilder("<addForeignKeyConstraint")
                .append(attr("constraintName", name))
                .append(attr("baseTableSchemaName", from.schema()))
                .append(attr("baseTableName", from.name()))
                .append(attr("baseColumnNames", r.columns().stream()
                        .map(p -> from.column(p.fromColumnId()).orElseThrow().name()).collect(Collectors.joining(","))))
                .append(attr("referencedTableSchemaName", to.schema()))
                .append(attr("referencedTableName", to.name()))
                .append(attr("referencedColumnNames", r.columns().stream()
                        .map(p -> to.column(p.toColumnId()).orElseThrow().name()).collect(Collectors.joining(","))));
        if (r.onDelete() != FkAction.NO_ACTION) {
            sb.append(attr("onDelete", r.onDelete().sql()));
        }
        if (r.onUpdate() != FkAction.NO_ACTION) {
            sb.append(attr("onUpdate", r.onUpdate().sql()));
        }
        x.line(2, sb + "/>");
        x.closeChangeSet();
    }

    private void createIndex(Xml x, Table t, Index i) {
        String name = Naming.index(t, i);
        String id = "index-" + t.schema() + "." + name;
        if (!"btree".equals(i.method()) || !Model.isBlank(i.where())) {
            // Liquibase's createIndex cannot express USING / WHERE: fall back to raw SQL.
            x.sqlChangeSet(id, ddl.createIndex(t, i), "DROP INDEX " + Identifiers.qualified(t.schema(), name) + ";");
            return;
        }
        x.openChangeSet(id);
        x.line(2, "<createIndex" + attr("schemaName", t.schema()) + attr("tableName", t.name())
                + attr("indexName", name) + (i.unique() ? attr("unique", "true") : "") + ">");
        for (String col : Naming.columnNames(t, i.columnIds())) {
            x.line(3, "<column" + attr("name", col) + "/>");
        }
        x.line(2, "</createIndex>");
        x.closeChangeSet();
    }

    private static String attr(String name, String value) {
        return " " + name + "=\"" + escape(value) + "\"";
    }

    private static String optAttr(String name, String value) {
        return Model.isBlank(value) ? "" : attr(name, value);
    }

    static String escape(String s) {
        return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                .replace("\"", "&quot;").replace("'", "&apos;");
    }

    private static String comment(String s) {
        return s.replace("--", "- -");
    }

    /** Tiny indenting writer. */
    private static final class Xml {
        private final StringBuilder sb = new StringBuilder();
        private final String author;

        Xml(String author) {
            this.author = author;
        }

        void line(int indent, String text) {
            sb.append("    ".repeat(indent)).append(text).append('\n');
        }

        void openChangeSet(String id) {
            openChangeSet(id, false);
        }

        void openChangeSet(String id, boolean runOnChange) {
            sb.append('\n');
            line(1, "<changeSet" + attr("id", id) + attr("author", author)
                    + (runOnChange ? attr("runOnChange", "true") : "") + ">");
        }

        void closeChangeSet() {
            line(1, "</changeSet>");
        }

        void sqlChangeSet(String id, String sql, String rollback) {
            sqlChangeSet(id, sql, rollback, false);
        }

        /** {@code rollback == null} writes an empty rollback (nothing to undo). */
        void sqlChangeSet(String id, String sql, String rollback, boolean runOnChange) {
            openChangeSet(id, runOnChange);
            line(2, "<sql><![CDATA[" + cdata(sql) + "]]></sql>");
            line(2, rollback == null ? "<rollback/>" : "<rollback><![CDATA[" + cdata(rollback) + "]]></rollback>");
            closeChangeSet();
        }

        static String cdata(String s) {
            return s.replace("]]>", "]]]]><![CDATA[>");
        }

        @Override
        public String toString() {
            return sb.toString();
        }
    }
}
